# Turns the translation tables in this folder (pl.tsv, de.tsv, ...: key, tab, text) into the C#
# tables the mod is built with (src/LivingFactions.Core/Texts.<code>.cs) and checks each of them
# against English: a line that is missing, or whose placeholders ({0}, {f}, ...) differ, is an error.
# Run:  python tools/lang/build.py
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, '..', '..', 'src', 'LivingFactions.Core')
CODES = ['pl', 'de', 'fr', 'es', 'pt']
# Lines every table must have besides those of the main one.
EXTRA = ['f_clan_raven', 'f_clan_wolf', 'f_clan_stag', 'f_fuling_horde', 'f_dvergr_hold', 'f_greydwarf_brood', 'f_draugr_court',
         'item_LF_WolfFangAxe', 'itemd_LF_WolfFangAxe', 'item_LF_StagHornAxe', 'itemd_LF_StagHornAxe'] + \
        ['%s_LF_%s' % (k, a) for a in ('RavenWingAxe', 'BlackgnawAxe', 'RuneAxe', 'RootAxe', 'BarrowMoonAxe',
                                                 'GreyBlade', 'AntlerBlade', 'BlackBeak', 'ObsidianSaber', 'RuneSword', 'RootClub', 'RustedBlade',
                                                 'WolfHideShield', 'StagTrailShield', 'RavenShield', 'BoneShield', 'CopperShield', 'BarkShield', 'BonePlateShield') for k in ('item', 'itemd')]

main = io.open(os.path.join(CORE, 'Texts.cs'), encoding='utf-8').read()
english = {}
for m in re.finditer(r'\{ "([^"]+)", new\[\] \{ "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)" \} \}', main):
    english[m.group(1)] = m.group(2)

def marks(text):
    return sorted(re.findall(r'\{[a-z0-9]+\}', text))

bad = 0
built = []
for code in CODES:
    path = os.path.join(HERE, code + '.tsv')
    if not os.path.exists(path):
        continue
    table = {}
    for n, line in enumerate(io.open(path, encoding='utf-8').read().split('\n'), 1):
        if not line.strip() or line.startswith('#'):
            continue
        if '\t' not in line:
            print('%s.tsv line %d: no tab' % (code, n)); bad += 1; continue
        key, text = line.split('\t', 1)
        if key in table:
            print('%s.tsv line %d: %s twice' % (code, n, key)); bad += 1
        table[key] = text
    for key, en in english.items():
        if key.startswith('lang_') and key != 'lang_auto':
            continue
        if key not in table:
            print('%s: missing %s' % (code, key)); bad += 1; continue
        if marks(table[key]) != marks(en):
            print('%s: %s has other placeholders than English: %s / %s' % (code, key, table[key], en)); bad += 1
        # Lines that are glued to what follows keep their trailing space.
        if en.endswith(' ') and not table[key].endswith(' '):
            table[key] += ' '
        if en.startswith(' ') and not table[key].startswith(' '):
            table[key] = ' ' + table[key]
    for key in EXTRA:
        if key not in table:
            print('%s: missing %s' % (code, key)); bad += 1
    for key in table:
        if key not in english and key not in EXTRA and not key.startswith('n_'):
            print('%s: unknown key %s' % (code, key)); bad += 1
    out = ['// Generated by tools/lang/build.py from tools/lang/%s.tsv. Change the table there, not here.' % code,
           'using System.Collections.Generic;', '', 'namespace LivingFactions.Core', '{', '    public static partial class Texts', '    {',
           '        private static Dictionary<string, string> Table_%s()' % code, '        {',
           '            return new Dictionary<string, string>', '            {']
    for key, text in table.items():
        out.append('                { "%s", "%s" },' % (key, text.replace('\\', '\\\\').replace('"', '\\"')))
    out += ['            };', '        }', '    }', '}', '']
    io.open(os.path.join(CORE, 'Texts.%s.cs' % code), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    built.append(code)

out = ['// Generated by tools/lang/build.py: which translation tables the mod is built with.',
       'namespace LivingFactions.Core', '{', '    public static partial class Texts', '    {', '        static Texts()', '        {']
for code in built:
    out.append('            More[System.Array.IndexOf(Codes, "%s")] = Table_%s();' % (code, code))
out += ['        }', '    }', '}', '']
io.open(os.path.join(CORE, 'Texts.Languages.cs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('built: %s; problems: %d' % (', '.join(built), bad))
sys.exit(1 if bad else 0)
